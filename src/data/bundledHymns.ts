/**
 * Find hymn by number or fuzzy title match
 */
export function findBundledHymn(query: string | number): BundledHymn | undefined {
  if (!query) return undefined;
  const qStr = String(query).trim().toLowerCase();
  const num = parseInt(qStr, 10);
  if (!isNaN(num)) {
    const byNum = BUNDLED_HYMNS.find(h => h.number === num);
    if (byNum) return byNum;
  }
  return BUNDLED_HYMNS.find(h => h.title.toLowerCase().includes(qStr));
}

